// Writes a built web application as C: for every file the complete HTTP responses (brotli,
// gzip, plain, and "not modified"), so the server sends them from read-only memory without
// touching the file system.
//   node tools/embed-assets.mjs <directory> > assets_gen.h
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { extname, join, relative, sep } from "node:path";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";

const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml", ".webmanifest": "application/manifest+json", ".json": "application/json",
  ".png": "image/png", ".ico": "image/x-icon", ".woff2": "font/woff2", ".txt": "text/plain; charset=utf-8",
};
const SECURITY =
  "Content-Security-Policy: default-src 'self'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'\r\n" +
  "X-Content-Type-Options: nosniff\r\nReferrer-Policy: no-referrer\r\n";

const root = process.argv[2];
if (!root) throw new Error("usage: embed-assets.mjs <directory>");
const files = readdirSync(root, { recursive: true, withFileTypes: true })
  .filter((e) => e.isFile() && !e.name.endsWith(".map"))
  .map((e) => relative(root, join(e.parentPath, e.name)).split(sep).join("/"))
  .sort();
if (!files.includes("index.html")) throw new Error(`${root} has no index.html: build the web application first`);

let out = "/* GENERATED by tools/embed-assets.mjs. Do not edit. */\n";
const array = (name, bytes) => `static const u8 ${name}[] = {${Array.from(bytes).join(",")}};\n`;
const rows = [];
files.forEach((file, i) => {
  if (!/^[A-Za-z0-9._\/-]+$/.test(file)) throw new Error(`unsupported file name: ${file}`);
  const body = readFileSync(join(root, file));
  const type = TYPES[extname(file)] ?? "application/octet-stream";
  // the build puts a content hash into the names under assets/
  const cache = /(^|\/)assets\//.test(file) ? "public, max-age=31536000, immutable" : "no-cache";
  const etag = `W/"${createHash("sha256").update(body).digest("hex").slice(0, 16)}"`;
  const common = `ETag: ${etag}\r\nCache-Control: ${cache}\r\nVary: Accept-Encoding\r\n`;
  const response = (encoding, data) => Buffer.concat([Buffer.from(
    `HTTP/1.1 200 OK\r\nContent-Type: ${type}\r\n${common}${SECURITY}` +
    (encoding ? `Content-Encoding: ${encoding}\r\n` : "") + `Content-Length: ${data.length}\r\n\r\n`), data]);
  const variant = (suffix, encoding, data) => {
    if (data.length >= body.length) return "{0, 0}";
    out += array(`A${i}_${suffix}`, response(encoding, data));
    return `{A${i}_${suffix}, sizeof A${i}_${suffix}}`;
  };
  const br = variant("BR", "br", brotliCompressSync(body, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }));
  const gzip = variant("GZ", "gzip", gzipSync(body, { level: 9 }));
  out += array(`A${i}_PLAIN`, response("", body));
  out += array(`A${i}_SAME`, Buffer.from(`HTTP/1.1 304 Not Modified\r\n${common}\r\n`));
  rows.push(`  {"/${file}", ${file.length + 1}, ${JSON.stringify(etag)}, ${br}, ${gzip}, {A${i}_PLAIN, sizeof A${i}_PLAIN}, {A${i}_SAME, sizeof A${i}_SAME}},`);
});
out += `static const asset ASSETS[] = {\n${rows.join("\n")}\n};\n#define ASSET_COUNT ${rows.length}\n`;
process.stdout.write(out);
